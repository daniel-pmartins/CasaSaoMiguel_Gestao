-- Estrutura permanente do módulo COMPRAS.

create table if not exists public.compras (
  id text primary key,
  situacao text not null,
  origem text not null default '',
  numero text not null default '',
  serie text not null default '',
  data_emissao date,
  chave_nfe text not null default '',
  fornecedor_id text references public.fornecedores(id),
  cnpj text not null default '',
  razao_social text not null default '',
  total_nota_cent text not null default '0',
  frete_nota_cent text not null default '0',
  desconto_nota_cent text not null default '0',
  outros_xml_cent text not null default '0',
  outros_externos_cent text not null default '0',
  justificativa_externos text not null default '',
  credito_usado_cent text not null default '0',
  criado_em timestamptz,
  atualizado_em timestamptz,
  observacoes text not null default ''
);

create table if not exists public.compras_itens (
  compra_id text not null references public.compras(id),
  item_id text not null,
  codigo_xml text not null default '',
  descricao_xml text not null default '',
  qtd_comprada_mili bigint not null default 0,
  qtd_recebida_mili bigint not null default 0,
  qtd_cancelada_mili bigint not null default 0,
  embalagem_mili bigint not null default 0,
  unidade_embalagem text not null default '',
  preco_unit_cent text not null default '0',
  valor_total_cent text not null default '0',
  insumo_id text references public.insumos(id),
  grupo_xml text not null default '',
  primary key (compra_id, item_id)
);

create table if not exists public.compras_itens_originais_xml (
  compra_id text not null references public.compras(id),
  item_id text not null,
  numero_linha_xml integer not null,
  codigo_xml text not null default '',
  descricao_xml text not null default '',
  quantidade_xml text not null default '',
  preco_unit_xml text not null default '',
  valor_total_xml text not null default '',
  unidade_xml text not null default '',
  primary key (compra_id, item_id, numero_linha_xml)
);

create table if not exists public.compras_pagamentos (
  compra_id text not null references public.compras(id),
  pagamento_id text not null,
  forma text not null default '',
  valor_cent text not null default '0',
  vencimento date,
  pago text not null default 'NÃO',
  data_pagamento date,
  cartao_id text not null default '',
  parcela integer not null default 1,
  total_parcelas integer not null default 1,
  primary key (compra_id, pagamento_id)
);

create table if not exists public.compras_pagamentos_externos (
  compra_id text not null references public.compras(id),
  pagamento_id text not null,
  forma text not null default '',
  valor_cent text not null default '0',
  vencimento date,
  pago text not null default 'NÃO',
  data_pagamento date,
  cartao_id text not null default '',
  parcela integer not null default 1,
  total_parcelas integer not null default 1,
  primary key (compra_id, pagamento_id)
);

create table if not exists public.compras_vinculos (
  id bigint generated by default as identity primary key,
  fornecedor_id text references public.fornecedores(id),
  codigo_xml text not null default '',
  descricao_xml text not null default '',
  preco_identificador text not null default '',
  insumo_id text references public.insumos(id),
  embalagem_mili bigint not null default 0,
  unidade text not null default '',
  atualizado_em timestamptz
);

create table if not exists public.compras_recebimentos (
  id text primary key,
  compra_id text not null references public.compras(id),
  item_id text not null,
  data timestamptz,
  qtd_comercial_mili bigint not null default 0,
  qtd_base_mili bigint not null default 0,
  custo_exato text not null default '0/1',
  movimento_id text not null default ''
);

create table if not exists public.compras_creditos (
  id text primary key,
  fornecedor_id text references public.fornecedores(id),
  origem_compra text not null default '',
  total_cent text not null default '0',
  usado_cent text not null default '0',
  justificativa text not null default '',
  data timestamptz
);

create table if not exists public.compras_usos_credito (
  id bigint generated by default as identity primary key,
  credito_id text not null references public.compras_creditos(id),
  compra_id text not null references public.compras(id),
  valor_cent text not null default '0',
  data timestamptz
);

create table if not exists public.compras_ajustes (
  id text primary key,
  compra_id text not null references public.compras(id),
  tipo text not null default '',
  item_id text not null default '',
  qtd_mili bigint not null default 0,
  valor_cent text not null default '0',
  parcela text not null default '',
  justificativa text not null default '',
  data timestamptz
);

create table if not exists public.compras_despesas_externas (
  id text primary key,
  compra_id text not null references public.compras(id),
  fornecedor_mercadoria_id text references public.fornecedores(id),
  valor_cent text not null default '0',
  justificativa text not null default '',
  data timestamptz,
  origem text not null default ''
);

create table if not exists public.compras_rascunhos (
  id text primary key,
  situacao text not null,
  fornecedor_nome text not null default '',
  criado_em timestamptz,
  atualizado_em timestamptz,
  versao integer not null default 1
);

create table if not exists public.compras_rascunho_partes (
  rascunho_id text not null references public.compras_rascunhos(id),
  versao integer not null,
  ordem integer not null,
  json_parcial text not null default '',
  primary key (rascunho_id, versao, ordem)
);

create index if not exists compras_fornecedor_idx on public.compras (fornecedor_id, atualizado_em);
create index if not exists compras_situacao_idx on public.compras (situacao, atualizado_em);
create index if not exists compras_itens_insumo_idx on public.compras_itens (insumo_id);
