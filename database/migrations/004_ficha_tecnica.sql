-- Estrutura permanente do módulo FICHA TÉCNICA.

create table if not exists public.ft_cadastros (
  ft_id text primary key,
  nome text not null,
  categoria text not null default '',
  status text not null,
  versao_atual integer not null default 1,
  criado_em timestamptz,
  atualizado_em timestamptz,
  observacoes text not null default '',
  excluido boolean not null default false
);

create table if not exists public.ft_versoes (
  ft_id text not null references public.ft_cadastros(ft_id),
  versao integer not null,
  data timestamptz,
  responsavel text not null default '',
  receita_json jsonb not null,
  motivo text not null default '',
  primary key (ft_id, versao)
);

create table if not exists public.ft_categorias (
  nome text primary key,
  criado_em timestamptz
);

create table if not exists public.ft_custos_manuais (
  insumo_id text primary key references public.insumos(id),
  unidade text not null,
  custo_exato text not null default '0/1',
  data timestamptz,
  origem text not null default '',
  observacao text not null default ''
);

create table if not exists public.ft_precos (
  id bigint generated by default as identity primary key,
  ft_id text not null references public.ft_cadastros(ft_id),
  config_key text not null,
  pdv text not null default '',
  data timestamptz,
  responsavel text not null default '',
  unique (ft_id, config_key, pdv)
);

create index if not exists ft_cadastros_categoria_idx on public.ft_cadastros (categoria, status);
create index if not exists ft_versoes_data_idx on public.ft_versoes (ft_id, data);
