-- Estrutura permanente do módulo ESTOQUE.
-- Frações exatas continuam armazenadas como texto "numerador/denominador".

create table if not exists public.estoque_saldos (
  insumo_id text primary key references public.insumos(id),
  quantidade_mili bigint not null default 0,
  valor_exato text not null default '0/1',
  pendente_exato text not null default '0/1',
  ultimo_custo_exato text not null default '0/1',
  atualizado_em timestamptz
);

create table if not exists public.estoque_inventarios (
  id text primary key,
  tipo text not null,
  status text not null,
  iniciado_em timestamptz,
  encerrado_em timestamptz,
  justificativa text not null default '',
  atualizado_em timestamptz
);

create table if not exists public.estoque_contagens (
  id bigint generated by default as identity primary key,
  inventario_id text not null references public.estoque_inventarios(id),
  insumo_id text not null references public.insumos(id),
  quantidade_mili bigint not null default 0,
  tam_embalagem text not null default '',
  unidade_embalagem text not null default '',
  preco_centavos text not null default '0',
  saldo_referencia_mili bigint not null default 0,
  momento_contagem timestamptz,
  compensar text not null default 'NÃO',
  gravado text not null default 'NÃO',
  atualizado_em timestamptz,
  unique (inventario_id, insumo_id)
);

create table if not exists public.estoque_operacoes (
  id text primary key,
  data timestamptz,
  movimento text not null,
  tipo text not null,
  referencia text not null default '',
  valor_impacto_exato text not null default '0/1',
  observacao text not null default ''
);

create table if not exists public.estoque_movimentacoes (
  id text primary key,
  operacao_id text not null references public.estoque_operacoes(id),
  data timestamptz,
  insumo_id text not null references public.insumos(id),
  quantidade_mili bigint not null default 0,
  valor_antes_exato text not null default '0/1',
  valor_depois_exato text not null default '0/1',
  pendente_antes_exato text not null default '0/1',
  pendente_depois_exato text not null default '0/1',
  descricao text not null default ''
);

create table if not exists public.estoque_inventario_final (
  inventario_id text not null references public.estoque_inventarios(id),
  insumo_id text not null references public.insumos(id),
  descricao text not null default '',
  unidade text not null default '',
  referencia_mili bigint not null default 0,
  contagem_mili bigint not null default 0,
  diferenca_mili bigint not null default 0,
  compensar text not null default 'NÃO',
  tam_embalagem text not null default '',
  un_embalagem text not null default '',
  preco_centavos text not null default '0',
  valor_antes_exato text not null default '0/1',
  valor_depois_exato text not null default '0/1',
  primary key (inventario_id, insumo_id)
);

create table if not exists public.estoque_detalhes_contagem (
  inventario_id text not null references public.estoque_inventarios(id),
  insumo_id text not null references public.insumos(id),
  sequencia integer not null,
  quantidade_mili bigint not null default 0,
  tamanho_mili bigint not null default 0,
  unidade text not null default '',
  ativo text not null default 'NÃO',
  registrado_em timestamptz,
  primary key (inventario_id, insumo_id, sequencia)
);

create table if not exists public.estoque_custos_referencia (
  insumo_id text primary key references public.insumos(id),
  unidade text not null,
  custo_exato text not null default '0/1',
  atualizado_em timestamptz,
  origem text not null default '',
  referencia text not null default ''
);

create table if not exists public.estoque_transicoes_insumos (
  id bigint generated by default as identity primary key,
  insumo_id text not null references public.insumos(id),
  data timestamptz,
  unidade_anterior text not null default '',
  unidade_nova text not null default '',
  controle_anterior text not null default '',
  controle_novo text not null default '',
  saldo_historico_mili bigint not null default 0,
  valor_historico_exato text not null default '0/1'
);

create table if not exists public.estoque_base_custo_nao_controlado (
  insumo_id text not null references public.insumos(id),
  unidade_base text not null,
  quantidade_referencia_mili bigint not null default 1000,
  valor_exato_da_unidade text not null default '0/1',
  origem text not null default '',
  atualizado_em timestamptz,
  primary key (insumo_id, unidade_base)
);

create table if not exists public.estoque_rascunhos_saida (
  id text primary key,
  status text not null,
  json_rascunho jsonb not null,
  criado_em timestamptz,
  atualizado_em timestamptz
);

create index if not exists estoque_contagens_insumo_idx on public.estoque_contagens (insumo_id);
create index if not exists estoque_movimentacoes_insumo_idx on public.estoque_movimentacoes (insumo_id, data);
create index if not exists estoque_operacoes_data_idx on public.estoque_operacoes (data);
